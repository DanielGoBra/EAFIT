/**
 * Build EAFIT-branded Canvas Controls JSON for ScrInventario, ScrPrestamos, ScrReservas.
 * Confirmed-working format rules (from iterative testing):
 *   - NO Version field in Template objects (pac-style minimal template)
 *   - VariantName: "ManualInput" for rectangle, "Label" for label,
 *                  "Button" for button, "TextInput" for textInput
 *   - Category: "Design" for ALL properties (Text, Color, Font, etc.)
 *   - No emoji in InvariantScript strings (use ASCII equivalents)
 *   - AllowAccessToGlobals: false for child controls
 * Run: node buildEafitScreens.js <outputDir>
 */
const fs = require('fs');
const OUT = process.argv[2] || 'C:/EAFIT/powerapps/canvas/msapp_v9_tmp/Controls';

// ── EAFIT Colors ───────────────────────────────────────────────────────────────
const C = {
  blue:      'RGBA(26, 92, 168, 1)',
  navy:      'RGBA(15, 61, 115, 1)',
  blueLight: 'RGBA(46, 123, 196, 1)',
  canvas:    'RGBA(238, 244, 252, 1)',
  white:     'RGBA(255, 255, 255, 1)',
  white70:   'RGBA(255, 255, 255, 0.70)',
  transparent: 'RGBA(0, 0, 0, 0)',
  textDark:  'RGBA(40, 40, 40, 1)',
  gray:      'RGBA(120, 120, 140, 1)',
};

// ── Template factory (NO Version — confirmed safe) ─────────────────────────────
const tpl = (name) => ({
  Id: `http://microsoft.com/appmagic/${name === 'textInput' ? 'textinput' : name}`,
  LastModifiedTimestamp: '0',
  Name: name,
  FirstParty: true,
  IsPremiumPcfControl: false,
  IsCustomGroupControlTemplate: false,
  CustomGroupControlTemplateName: '',
  IsComponentDefinition: false,
  OverridableProperties: {},
});

// VariantName per control type
const VARIANT = {
  screen: '', rectangle: 'ManualInput', label: 'Label',
  button: 'Button', textInput: 'TextInput',
};
const STYLE = {
  screen: 'defaultScreenStyle', rectangle: 'defaultRectangleStyle',
  label: 'defaultLabelStyle', button: 'defaultButtonStyle',
  textInput: 'defaultTextInputStyle',
};

// ── ID counter ─────────────────────────────────────────────────────────────────
let _uid = 200;
const uid = () => String(++_uid);

// ── Rule / control helpers ─────────────────────────────────────────────────────
const D = (prop, val) => ({ Property: prop, Category: 'Design', InvariantScript: val, RuleProviderType: 'Unknown' });
const B = (prop, val) => ({ Property: prop, Category: 'Behavior', InvariantScript: val, RuleProviderType: 'Unknown' });

function mkCtrl(type, name, parent, publishIdx, rules, children = []) {
  return {
    Type: 'ControlInfo',
    Name: name,
    HasDynamicProperties: false,
    Template: tpl(type),
    Index: 0,
    PublishOrderIndex: publishIdx,
    VariantName: VARIANT[type],
    LayoutName: '',
    MetaDataIDKey: '',
    PersistMetaDataIDKey: false,
    IsFromScreenLayout: false,
    StyleName: STYLE[type],
    Parent: parent,
    IsDataControl: false,
    AllowAccessToGlobals: false,
    OptimizeForDevices: 'Off',
    IsGroupControl: false,
    IsAutoGenerated: false,
    Rules: rules,
    ControlPropertyState: rules.map(r => r.Property),
    IsLocked: false,
    ControlUniqueId: uid(),
    Children: children,
  };
}

// ── Reusable UI blocks ──────────────────────────────────────────────────────────

function mkHeader(screenName, title, base) {
  return [
    mkCtrl('rectangle', `RctHdr${screenName}`, screenName, base, [
      D('X','0'), D('Y','0'), D('Width','Parent.Width'), D('Height','64'),
      D('Fill', C.blue), D('BorderThickness','0'),
    ]),
    mkCtrl('label', `LblHdr${screenName}`, screenName, base + 1, [
      D('X','20'), D('Y','0'), D('Width','Parent.Width - 40'), D('Height','64'),
      D('Fill', C.transparent),
      D('Text', `"${title}"`), D('Color', C.white),
      D('Size','20'), D('FontWeight','FontWeight.Bold'),
      D('Align','Align.Left'), D('VerticalAlign','VerticalAlign.Middle'),
    ]),
  ];
}

function mkFooter(screenName, base) {
  return mkCtrl('rectangle', `RctFtr${screenName}`, screenName, base, [
    D('X','0'), D('Y','Parent.Height - 56'), D('Width','Parent.Width'), D('Height','56'),
    D('Fill', C.blue), D('BorderThickness','0'),
  ]);
}

function mkSearchBar(screenName, base) {
  return [
    mkCtrl('rectangle', `RctSearch${screenName}`, screenName, base, [
      D('X','16'), D('Y','76'), D('Width','Parent.Width - 32'), D('Height','40'),
      D('Fill', C.white), D('BorderColor', C.blueLight), D('BorderThickness','1'),
    ]),
    mkCtrl('label', `LblSearch${screenName}`, screenName, base + 1, [
      D('X','24'), D('Y','76'), D('Width','Parent.Width - 48'), D('Height','40'),
      D('Fill', C.transparent),
      D('Text','"Buscar..."'), D('Color', C.gray),
      D('Size','14'), D('VerticalAlign','VerticalAlign.Middle'),
    ]),
  ];
}

function mkColHeaders(screenName, columns, base) {
  const controls = [
    mkCtrl('rectangle', `RctCols${screenName}`, screenName, base, [
      D('X','0'), D('Y','128'), D('Width','Parent.Width'), D('Height','40'),
      D('Fill', C.navy), D('BorderThickness','0'),
    ]),
  ];
  columns.forEach((col, i) => {
    const xPct = (i / columns.length * 100).toFixed(1);
    controls.push(mkCtrl('label', `LblCol${i}${screenName}`, screenName, base + 1 + i, [
      D('X', `Parent.Width * ${(i/columns.length).toFixed(3)}`),
      D('Y','128'),
      D('Width', `Parent.Width / ${columns.length}`),
      D('Height','40'),
      D('Fill', C.transparent),
      D('Text', `"${col}"`), D('Color', C.white),
      D('Size','13'), D('FontWeight','FontWeight.Semibold'),
      D('Align','Align.Left'), D('VerticalAlign','VerticalAlign.Middle'),
      D('PaddingLeft','12'),
    ]));
  });
  return controls;
}

function mkDivider(screenName, yPos, base) {
  return mkCtrl('rectangle', `RctDiv${screenName}`, screenName, base, [
    D('X','0'), D('Y', String(yPos)), D('Width','Parent.Width'), D('Height','2'),
    D('Fill', C.blueLight), D('BorderThickness','0'),
  ]);
}

function mkEmptyHint(screenName, msg, base) {
  return mkCtrl('label', `LblHint${screenName}`, screenName, base, [
    D('X','0'), D('Y','200'), D('Width','Parent.Width'), D('Height','60'),
    D('Fill', C.transparent),
    D('Text', `"${msg}"`), D('Color', C.gray),
    D('Size','14'), D('Align','Align.Center'), D('VerticalAlign','VerticalAlign.Middle'),
  ]);
}

// ── Screen factory ─────────────────────────────────────────────────────────────
const SCREEN_RULES = [
  D('Fill', C.canvas),
  D('ImagePosition','ImagePosition.Fit'),
  D('Height','Max(App.Height, App.MinScreenHeight)'),
  D('Width','Max(App.Width, App.MinScreenWidth)'),
  D('Size','1 + CountRows(App.SizeBreakpoints) - CountIf(App.SizeBreakpoints, Value >= Self.Width)'),
  D('Orientation','If(Self.Width < Self.Height, Layout.Vertical, Layout.Horizontal)'),
  D('LoadingSpinner','LoadingSpinner.None'),
  D('LoadingSpinnerColor','RGBA(0, 120, 212, 1)'),
];

function mkScreen(name, id, publishIdx, children) {
  return {
    TopParent: {
      Type: 'ControlInfo',
      Name: name,
      Template: tpl('screen'),
      Index: 0,
      PublishOrderIndex: publishIdx,
      VariantName: '',
      LayoutName: '',
      MetaDataIDKey: '',
      PersistMetaDataIDKey: false,
      IsFromScreenLayout: false,
      StyleName: 'defaultScreenStyle',
      Parent: '',
      IsDataControl: false,
      AllowAccessToGlobals: true,
      OptimizeForDevices: 'Off',
      IsGroupControl: false,
      IsAutoGenerated: false,
      Rules: SCREEN_RULES,
      ControlPropertyState: SCREEN_RULES.map(r => r.Property),
      IsLocked: false,
      ControlUniqueId: String(id),
      Children: children,
    },
  };
}

// ── Build the 3 screens ────────────────────────────────────────────────────────

// ScrInventario ─────────────────────────────────────────────────────────────────
const invChildren = [
  ...mkHeader('ScrInventario', 'Inventario', 300),
  ...mkSearchBar('ScrInventario', 310),
  ...mkColHeaders('ScrInventario', ['Articulo', 'Categoria', 'Estado', 'Cant.'], 320),
  mkDivider('ScrInventario', 168, 330),
  mkEmptyHint('ScrInventario', 'Conecta SharePoint para ver el inventario', 340),
  mkFooter('ScrInventario', 350),
];

// ScrPrestamos ──────────────────────────────────────────────────────────────────
const presChildren = [
  ...mkHeader('ScrPrestamos', 'Prestamos', 400),
  ...mkColHeaders('ScrPrestamos', ['Articulo', 'Docente', 'F.Prestamo', 'Estado'], 410),
  mkDivider('ScrPrestamos', 128, 420),
  mkEmptyHint('ScrPrestamos', 'Conecta SharePoint para ver los prestamos', 430),
  mkFooter('ScrPrestamos', 440),
];

// ScrReservas ───────────────────────────────────────────────────────────────────
const resChildren = [
  ...mkHeader('ScrReservas', 'Reservas', 500),
  ...mkColHeaders('ScrReservas', ['Sala', 'Docente', 'Fecha', 'Estado'], 510),
  mkDivider('ScrReservas', 128, 520),
  mkEmptyHint('ScrReservas', 'Conecta SharePoint para ver las reservas', 530),
  mkFooter('ScrReservas', 540),
];

// ── Write files ────────────────────────────────────────────────────────────────
if (!fs.existsSync(OUT)) fs.mkdirSync(OUT, { recursive: true });

const s9  = mkScreen('ScrInventario', 9,  10, invChildren);
const s10 = mkScreen('ScrPrestamos',  10, 11, presChildren);
const s11 = mkScreen('ScrReservas',   11, 12, resChildren);

fs.writeFileSync(OUT + '/9.json',  JSON.stringify(s9,  null, 2));
fs.writeFileSync(OUT + '/10.json', JSON.stringify(s10, null, 2));
fs.writeFileSync(OUT + '/11.json', JSON.stringify(s11, null, 2));

const sz = (j) => (JSON.stringify(j).length / 1024).toFixed(1) + ' KB';
console.log('ScrInventario:', sz(s9));
console.log('ScrPrestamos: ', sz(s10));
console.log('ScrReservas:  ', sz(s11));
console.log('All 3 EAFIT screens built in: ' + OUT);
