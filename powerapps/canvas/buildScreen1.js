/**
 * Build Screen1 dashboard for EAFIT Control MVP.
 * EAFIT brand: logo, campus background, yellow accents, navy palette.
 * Controls: rectangle (ManualInput), label (Label), image (Image).
 * Category "Design" for visual, "Behavior" for OnSelect.
 */
const fs = require('fs');
const OUT = process.argv[2] || 'C:/EAFIT/powerapps/canvas/msapp_v9_tmp/Controls';

// ── EAFIT Colors ──────────────────────────────────────────────────────────────
const C = {
  blue:        'RGBA(26, 92, 168, 1)',
  navy:        'RGBA(15, 61, 115, 1)',
  blueLight:   'RGBA(46, 123, 196, 1)',
  canvas:      'RGBA(238, 244, 252, 1)',
  white:       'RGBA(255, 255, 255, 1)',
  textDark:    'RGBA(15, 61, 115, 1)',   // navy for titles
  textBody:    'RGBA(26, 39, 66, 1)',    // near-navy body text
  gray:        'RGBA(107, 112, 128, 1)',
  yellow:      'RGBA(247, 181, 0, 1)',
  yellowDark:  'RGBA(204, 150, 0, 1)',
  yellowTint:  'RGBA(255, 248, 225, 1)',
  transparent: 'RGBA(0, 0, 0, 0)',
  overlay:     'RGBA(238, 244, 252, 0.88)', // light canvas overlay for background photo
};

// ── Template factory (NO Version) ────────────────────────────────────────────
const tpl = (name) => ({
  Id: `http://microsoft.com/appmagic/${name}`,
  LastModifiedTimestamp: '0',
  Name: name,
  FirstParty: true,
  IsPremiumPcfControl: false,
  IsCustomGroupControlTemplate: false,
  CustomGroupControlTemplateName: '',
  IsComponentDefinition: false,
  OverridableProperties: {},
});

const VARIANT = {
  screen:    '',
  rectangle: 'ManualInput',
  label:     'Label',
  button:    'Button',
};
const STYLE = {
  screen:    'defaultScreenStyle',
  rectangle: 'defaultRectangleStyle',
  label:     'defaultLabelStyle',
  button:    'defaultButtonStyle',
};

// ── Rule helpers ─────────────────────────────────────────────────────────────
const D = (p, v) => ({ Property: p, Category: 'Design',   InvariantScript: v, RuleProviderType: 'Unknown' });
const B = (p, v) => ({ Property: p, Category: 'Behavior', InvariantScript: v, RuleProviderType: 'Unknown' });

let _uid = 99;
const uid = () => String(++_uid);

function mkCtrl(type, name, parent, pubIdx, rules, children = []) {
  return {
    Type: 'ControlInfo', Name: name, HasDynamicProperties: false,
    Template: tpl(type), Index: 0, PublishOrderIndex: pubIdx,
    VariantName: VARIANT[type], LayoutName: '', MetaDataIDKey: '',
    PersistMetaDataIDKey: false, IsFromScreenLayout: false,
    StyleName: STYLE[type], Parent: parent,
    IsDataControl: false, AllowAccessToGlobals: false,
    OptimizeForDevices: 'Off', IsGroupControl: false, IsAutoGenerated: false,
    Rules: rules, ControlPropertyState: rules.map(r => r.Property),
    IsLocked: false, ControlUniqueId: uid(), Children: children,
  };
}

// ── Layout constants ─────────────────────────────────────────────────────────
const HDR_H  = 72;
const PAD    = 20;
const GAP    = 16;
const CARD_W = `(Parent.Width - ${PAD * 2} - ${GAP}) / 2`;
const CARD_H = `(Parent.Height - ${HDR_H} - ${PAD} - ${GAP} - ${PAD}) / 2`;
const ROW1_Y = HDR_H + PAD;
const ROW2_Y = `${ROW1_Y} + (Parent.Height - ${HDR_H} - ${PAD} - ${GAP} - ${PAD}) / 2 + ${GAP}`;
const COL1_X = PAD;
const COL2_X = `${PAD} + (Parent.Width - ${PAD * 2} - ${GAP}) / 2 + ${GAP}`;

// ── Card builder ─────────────────────────────────────────────────────────────
function mkCard(n, xExpr, yExpr, icon, title, desc, targetScreen, pubBase) {
  const controls = [];

  // White card background with subtle navy border
  controls.push(mkCtrl('rectangle', `RctCard${n}`, 'Screen1', pubBase, [
    D('X', xExpr), D('Y', yExpr),
    D('Width', CARD_W), D('Height', CARD_H),
    D('Fill', C.white),
    D('BorderColor', 'RGBA(203, 213, 225, 1)'), D('BorderThickness', '1'),
    B('OnSelect', `Navigate(${targetScreen})`),
  ]));

  // Yellow accent bar (top of card, 6px)
  controls.push(mkCtrl('rectangle', `RctAccent${n}`, 'Screen1', pubBase + 1, [
    D('X', xExpr), D('Y', yExpr),
    D('Width', CARD_W), D('Height', '6'),
    D('Fill', C.yellow), D('BorderThickness', '0'),
  ]));

  // Icon label — centered, blue
  controls.push(mkCtrl('label', `LblIcon${n}`, 'Screen1', pubBase + 2, [
    D('X', xExpr), D('Y', `${yExpr} + 14`),
    D('Width', CARD_W), D('Height', '48'),
    D('Fill', C.transparent),
    D('Text', `"${icon}"`), D('Color', C.blue),
    D('Size', '20'), D('Align', 'Align.Center'),
    D('VerticalAlign', 'VerticalAlign.Middle'),
    D('FontWeight', 'FontWeight.Bold'),
  ]));

  // Title — navy, bold
  controls.push(mkCtrl('label', `LblTitle${n}`, 'Screen1', pubBase + 3, [
    D('X', `${xExpr} + 16`), D('Y', `${yExpr} + 68`),
    D('Width', `${CARD_W} - 32`), D('Height', '28'),
    D('Fill', C.transparent),
    D('Text', `"${title}"`), D('Color', C.navy),
    D('Size', '15'), D('FontWeight', 'FontWeight.Bold'),
    D('VerticalAlign', 'VerticalAlign.Middle'),
  ]));

  // Count — yellow, large
  controls.push(mkCtrl('label', `LblCount${n}`, 'Screen1', pubBase + 4, [
    D('X', `${xExpr} + 16`), D('Y', `${yExpr} + 100`),
    D('Width', `${CARD_W} - 32`), D('Height', '56'),
    D('Fill', C.transparent),
    D('Text', '"--"'), D('Color', C.yellow),
    D('Size', '40'), D('FontWeight', 'FontWeight.Bold'),
    D('VerticalAlign', 'VerticalAlign.Middle'),
  ]));

  // Description — gray small
  controls.push(mkCtrl('label', `LblDesc${n}`, 'Screen1', pubBase + 5, [
    D('X', `${xExpr} + 16`), D('Y', `${yExpr} + 158`),
    D('Width', `${CARD_W} - 32`), D('Height', '24'),
    D('Fill', C.transparent),
    D('Text', `"${desc}"`), D('Color', C.gray),
    D('Size', '12'), D('VerticalAlign', 'VerticalAlign.Middle'),
  ]));

  // "Ver →" button rectangle — blue, bottom-right
  controls.push(mkCtrl('rectangle', `RctBtn${n}`, 'Screen1', pubBase + 6, [
    D('X', xExpr), D('Y', `${yExpr} + ${CARD_H} - 44`),
    D('Width', CARD_W), D('Height', '44'),
    D('Fill', C.blue), D('BorderThickness', '0'),
    B('OnSelect', `Navigate(${targetScreen})`),
  ]));

  // Button label
  controls.push(mkCtrl('label', `LblBtn${n}`, 'Screen1', pubBase + 7, [
    D('X', xExpr), D('Y', `${yExpr} + ${CARD_H} - 44`),
    D('Width', CARD_W), D('Height', '44'),
    D('Fill', C.transparent),
    D('Text', '"Ver →"'), D('Color', C.white),
    D('Size', '14'), D('FontWeight', 'FontWeight.Semibold'),
    D('Align', 'Align.Center'), D('VerticalAlign', 'VerticalAlign.Middle'),
  ]));

  return controls;
}

// ── Screen1 rules — campus background photo ───────────────────────────────────
const SCREEN_RULES = [
  D('Fill', C.canvas),
  D('Height', 'Max(App.Height, App.MinScreenHeight)'),
  D('Width', 'Max(App.Width, App.MinScreenWidth)'),
  D('Size', '1 + CountRows(App.SizeBreakpoints) - CountIf(App.SizeBreakpoints, Value >= Self.Width)'),
  D('Orientation', 'If(Self.Width < Self.Height, Layout.Vertical, Layout.Horizontal)'),
  D('LoadingSpinner', 'LoadingSpinner.None'),
  D('LoadingSpinnerColor', 'RGBA(0, 120, 212, 1)'),
];

// ── Assemble Screen1 children ─────────────────────────────────────────────────
const children = [

  // ── Translucent overlay (covers campus photo, preserves light canvas feel) ──
  mkCtrl('rectangle', 'RctOverlay', 'Screen1', 4, [
    D('X', '0'), D('Y', '0'),
    D('Width', 'Parent.Width'), D('Height', 'Parent.Height'),
    D('Fill', C.overlay), D('BorderThickness', '0'),
  ]),

  // ── Header bar (navy full-width) ──────────────────────────────────────────
  mkCtrl('rectangle', 'RctHdrScreen1', 'Screen1', 10, [
    D('X', '0'), D('Y', '0'),
    D('Width', 'Parent.Width'), D('Height', String(HDR_H)),
    D('Fill', C.navy), D('BorderThickness', '0'),
  ]),

  // Header title label (full width)
  mkCtrl('label', 'LblHdrScreen1', 'Screen1', 12, [
    D('X', '20'), D('Y', '0'),
    D('Width', 'Parent.Width - 40'), D('Height', String(HDR_H)),
    D('Fill', C.transparent),
    D('Text', '"Universidad EAFIT  ·  Control de Idiomas"'), D('Color', C.white),
    D('Size', '18'), D('FontWeight', 'FontWeight.Bold'),
    D('Align', 'Align.Left'), D('VerticalAlign', 'VerticalAlign.Middle'),
  ]),

  // Yellow accent line under header
  mkCtrl('rectangle', 'RctHdrAccent', 'Screen1', 13, [
    D('X', '0'), D('Y', String(HDR_H)),
    D('Width', 'Parent.Width'), D('Height', '3'),
    D('Fill', C.yellow), D('BorderThickness', '0'),
  ]),

  // ── 4 Cards ───────────────────────────────────────────────────────────────
  ...mkCard('1', String(COL1_X), String(ROW1_Y), 'Inventario', 'Inventario', 'Articulos registrados', 'ScrInventario', 20),
  ...mkCard('2', COL2_X,         String(ROW1_Y), 'Prestamos',  'Prestamos',  'Prestamos activos',     'ScrPrestamos',  30),
  ...mkCard('3', String(COL1_X), ROW2_Y,         'Reservas',  'Reservas',   'Reservas pendientes',   'ScrReservas',   40),
  ...mkCard('4', COL2_X,         ROW2_Y,         'Asistente IA', 'Asistente IA', 'Consultas con Gemma', 'ScrInventario', 50),
];

// ── Write Controls/4.json ────────────────────────────────────────────────────
const screen1 = {
  TopParent: {
    Type: 'ControlInfo', Name: 'Screen1',
    Template: tpl('screen'),
    Index: 0, PublishOrderIndex: 1,
    VariantName: '', LayoutName: '', MetaDataIDKey: '',
    PersistMetaDataIDKey: false, IsFromScreenLayout: false,
    StyleName: 'defaultScreenStyle',
    Parent: '', IsDataControl: false, AllowAccessToGlobals: true,
    OptimizeForDevices: 'Off', IsGroupControl: false, IsAutoGenerated: false,
    Rules: SCREEN_RULES,
    ControlPropertyState: SCREEN_RULES.map(r => r.Property),
    IsLocked: false, ControlUniqueId: '4',
    Children: children,
  },
};

fs.writeFileSync(OUT + '/4.json', JSON.stringify(screen1, null, 2));
console.log('Screen1 written:', children.length, 'controls, IDs 100-' + _uid);
